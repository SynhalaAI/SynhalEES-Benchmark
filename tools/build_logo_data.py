#!/usr/bin/env python3
"""Regenerate docs/assets/logo-data.js from docs/assets/logos/*.svg + icon.png.

The static site embeds provider logos and the brand icon as data URLs so
canvas PNG exports keep their icons on file:// pages (data: URLs never
taint the canvas; Chrome taints file-origin images).

Usage:

    python tools/build_logo_data.py           # regenerate docs/assets/logo-data.js
    python tools/build_logo_data.py --check   # verify it is up to date (CI gate)
    python tools/build_logo_data.py --stdout  # print to stdout instead of writing

The generated file carries a SOURCE-SHA256 checksum of its source files;
--check recomputes it and fails with exit 1 when the embedded data is stale
(a logo was added/edited without regenerating). CI runs --check on every
push and pull request (.github/workflows/logo-data.yml).

Stdlib only. Pillow is optional: when installed, raster-wrapped SVGs
(Inkscape exports with an embedded base64 bitmap) are downscaled to 96px
PNG; without it they are embedded at full size (larger output, still valid).
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import io
import re
import sys
from pathlib import Path
from urllib.parse import quote

try:
    from PIL import Image
except ImportError:  # optional - only used to shrink raster-wrapped SVGs
    Image = None

ROOT = Path(__file__).resolve().parent.parent
LOGOS = ROOT / "docs" / "assets" / "logos"
ICON = ROOT / "docs" / "assets" / "icon.png"
OUT = ROOT / "docs" / "assets" / "logo-data.js"
MARKER = "SOURCE-SHA256: "


def source_files():
    return sorted(LOGOS.glob("*.svg"), key=lambda p: p.name.lower()) + [ICON]


def source_hash():
    h = hashlib.sha256()
    for p in source_files():
        h.update(p.name.encode("utf-8"))
        h.update(b"\0")
        h.update(p.read_bytes())
        h.update(b"\0")
    return h.hexdigest()


def clean(txt):
    txt = re.sub(r"<\?.*?\?>", "", txt, flags=re.S)
    txt = re.sub(r"<!DOCTYPE[^>]*>", "", txt, flags=re.S)
    txt = re.sub(r"<!--.*?-->", "", txt, flags=re.S)
    return txt.strip()


def shrink(s):
    """Round long decimal strings in path data (logos render at ~20px)."""
    return re.sub(r"\d+\.\d+", lambda m: ("%.1f" % float(m.group(0))).rstrip("0").rstrip("."), s)


def raster_dataurl(txt):
    """SVG wrapper around a base64 bitmap (Inkscape export) -> plain image data URL."""
    m = re.search(r"data:image/([a-zA-Z]+);base64,([A-Za-z0-9+/=\s]+)", txt)
    fmt = m.group(1).lower()
    raw = base64.b64decode(re.sub(r"\s", "", m.group(2)))
    if Image is not None:
        im = Image.open(io.BytesIO(raw))
        im.thumbnail((96, 96), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, "PNG", optimize=True)
        raw, fmt = buf.getvalue(), "png"
    else:
        print("warning: Pillow not installed; embedding a raster logo at full size",
              file=sys.stderr)
    return "data:image/%s;base64,%s" % (fmt, base64.b64encode(raw).decode("ascii"))


def svg_dataurl(txt):
    txt = clean(txt)
    if len(txt) > 20000:
        txt = shrink(txt)
    # concrete intrinsic size so canvas drawImage works in every browser
    m = re.search(r"<svg\b[^>]*>", txt)
    tag = m.group(0)
    newtag = re.sub(r"\bwidth=\"[^\"]*\"", "width=\"24\"", tag)
    newtag = re.sub(r"\bheight=\"[^\"]*\"", "height=\"24\"", newtag)
    if "width=\"24\"" not in newtag:
        newtag = newtag.replace("<svg", "<svg width=\"24\"", 1)
    if "height=\"24\"" not in newtag:
        newtag = newtag.replace("<svg", "<svg height=\"24\"", 1)
    txt = txt.replace(tag, newtag, 1)
    return "data:image/svg+xml," + quote(txt, safe="")


def build():
    lines = [
        "/* GENERATED by tools/build_logo_data.py -- do not edit by hand.",
        "   Provider logos + brand icon embedded as data URLs so the canvas PNG export",
        "   works on file:// pages (data: URLs never taint the canvas).",
        "   After adding/editing assets/logos/*.svg or assets/icon.png, run:",
        "       python tools/build_logo_data.py",
        "   " + MARKER + source_hash() + " */",
        "window.SYNHALEES_LOGOS = {",
    ]
    for p in sorted(LOGOS.glob("*.svg"), key=lambda p: p.name.lower()):
        txt = p.read_text(encoding="utf-8")
        url = raster_dataurl(txt) if ("base64" in txt and "<image" in txt) else svg_dataurl(txt)
        lines.append("  \"%s\": \"%s\"," % (p.stem, url))
    lines.append("};")
    ic64 = base64.b64encode(ICON.read_bytes()).decode("ascii")
    lines.append("window.SYNHALEES_BRAND_ICON = \"data:image/png;base64," + ic64 + "\";")
    lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="fail (exit 1) if logo-data.js is stale or missing")
    ap.add_argument("--stdout", action="store_true",
                    help="print the generated file to stdout instead of writing it")
    args = ap.parse_args()

    if args.check:
        if not OUT.exists():
            print("ERROR: %s is missing. Run: python tools/build_logo_data.py" % OUT,
                  file=sys.stderr)
            return 1
        m = re.search(r"SOURCE-SHA256: ([0-9a-f]{64})", OUT.read_text(encoding="utf-8"))
        if not m:
            print("ERROR: %s has no SOURCE-SHA256 marker. Regenerate: "
                  "python tools/build_logo_data.py" % OUT, file=sys.stderr)
            return 1
        if m.group(1) != source_hash():
            print("ERROR: docs/assets/logo-data.js is STALE - a logo in "
                  "docs/assets/logos/ or docs/assets/icon.png changed without "
                  "regenerating.", file=sys.stderr)
            print("Run: python tools/build_logo_data.py  and commit the result.",
                  file=sys.stderr)
            return 1
        print("OK: docs/assets/logo-data.js matches its sources")
        return 0

    js = build()
    if args.stdout:
        sys.stdout.write(js)
        return 0
    OUT.write_text(js, encoding="utf-8", newline="\n")
    print("wrote %s (%d bytes, %d logos + brand icon)" % (OUT, len(js.encode("utf-8")),
          len(list(LOGOS.glob("*.svg")))))
    return 0


if __name__ == "__main__":
    sys.exit(main())