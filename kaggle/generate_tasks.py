"""Generate the 17 SynhalEES task files for Kaggle Benchmarks.

Outputs to ``kaggle/tasks/``:

- 15 pillar tasks (text rows of each pillar)
- 1 vision task (all pillars, image inputs)
- 1 audio task (all pillars, audio inputs)

Regenerate whenever pillars change::

    python kaggle/generate_tasks.py

Push everything (after ``kaggle b init -y``)::

    Get-ChildItem kaggle/tasks/*.py | % { kaggle b t push $_.FullName }
"""

from __future__ import annotations

from pathlib import Path

from synhalees import data as syn_data

OUT_DIR = Path(__file__).resolve().parent / "tasks"
TEMPLATE = r"""
# SynhalEES Kaggle task: @TITLE@ (@MODALITY@). Auto-generated by kaggle/generate_tasks.py.

import subprocess
import sys

subprocess.run(
    [sys.executable, "-m", "pip", "install", "-q",
     "git+https://github.com/SynhalaAI/SynhalEES-Benchmark.git"],
    check=True,
)

import kaggle_benchmarks as kbench

from synhalees import data as syn_data
from synhalees.evaluators import score_response

PILLAR = @PILLAR@  # None -> all pillars
MODALITY = "@MODALITY@"

_JUDGE_CRITERIA = (
    "The response conveys the same meaning as the reference answer: "
    "'{ground_truth}'. Wording may differ; the meaning must match.",
    "The response reads like a native Sri Lankan Sinhala speaker wrote it -- "
    "natural register and idiom, not translated-sounding English.",
)


def _rows():
    pillars = [PILLAR] if PILLAR else syn_data.list_pillars()
    rows = []
    for pillar in pillars:
        if MODALITY == "text":
            for it in syn_data.load_text(pillar):
                rows.append({"id": it.id, "prompt": it.prompt,
                             "ground_truth": it.ground_truth,
                             "eval_type": it.eval_type, "media_path": ""})
        else:
            loader = syn_data.load_vision if MODALITY == "vision" else syn_data.load_audio
            try:
                items = loader(pillar, strict=False)
            except FileNotFoundError:
                items = []
            for it in items:
                media = it.image_path if MODALITY == "vision" else it.audio_path
                if media.is_file():
                    rows.append({"id": it.id, "prompt": it.question,
                                 "ground_truth": it.ground_truth,
                                 "eval_type": it.eval_type,
                                 "media_path": str(media)})
    return rows


@kbench.task(name="@TASK_NAME@_item", store_task=False)
def synhalees_item(llm, id: str, prompt: str, ground_truth: str,
                   eval_type: str, media_path: str = "") -> dict:
    '''Score one item (sub-task; not stored top-level).'''
    if MODALITY == "vision":
        from kaggle_benchmarks.content_types import images
        response = llm.prompt(prompt, image=images.from_path(media_path))
    elif MODALITY == "audio":
        from kaggle_benchmarks.content_types import audios
        response = llm.prompt(prompt, audio=audios.from_path(media_path))
    else:
        response = llm.prompt(prompt)

    judge_passed = None
    if eval_type == "llm_judge":
        report = kbench.assertions.assess_response_with_judge(
            criteria=[c.format(ground_truth=ground_truth) for c in _JUDGE_CRITERIA],
            response_text=response,
            judge_llm=kbench.judge_llm,
        )
        judge_passed = all(r.passed for r in report.results)
    return {"id": id, "is_correct": score_response(
        response, ground_truth, eval_type, judge_passed=judge_passed)}


@kbench.task(name="@TASK_NAME@", description="@DESC@")
def synhalees_task(llm) -> float:
    '''Evaluate @TITLE@ (@MODALITY@); return accuracy in [0, 1].'''
    import pandas as pd

    rows = _rows()
    if not rows:
        raise ValueError(
            "No runnable @MODALITY@ rows for @TITLE@ yet -- media files may "
            "not be committed under benchmark_data/."
        )
    with kbench.client.enable_cache():
        runs = synhalees_item.evaluate(
            llm=[llm], evaluation_data=pd.DataFrame(rows),
            n_jobs=2, max_attempts=2, on_failure="continue",
            remove_run_files=True,
        )
    correct = runs.as_dataframe().result.str.get("is_correct").astype("boolean").fillna(False)
    return float(correct.mean())


# Required by the Kaggle Benchmarks workflow: the file executes the task.
synhalees_task.run(kbench.llm)
""".lstrip()
def _render(pillar, modality, task_name, title, desc) -> str:
    return (
        TEMPLATE
        .replace("@PILLAR@", repr(pillar))
        .replace("@MODALITY@", modality)
        .replace("@TASK_NAME@", task_name)
        .replace("@TITLE@", title)
        .replace("@DESC@", desc)
    )


def main() -> None:
    import sys

    out_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []

    for slug in syn_data.list_pillars():
        title = slug.partition("_")[2].replace("_", " ").title()
        path = out_dir / f"{slug}.py"
        path.write_text(
            _render(
                slug, "text", f"synhalees_{slug}", title,
                f"SynhalEES pillar {slug}: native Sinhala text accuracy.",
            ),
            encoding="utf-8",
        )
        written.append(path)

    for modality in ("vision", "audio"):
        path = out_dir / f"{modality}.py"
        path.write_text(
            _render(
                None, modality, f"synhalees_{modality}", f"All Pillars ({modality})",
                f"SynhalEES {modality} modality across all 15 pillars.",
            ),
            encoding="utf-8",
        )
        written.append(path)

    print(f"Generated {len(written)} task files in {out_dir}")


if __name__ == "__main__":
    main()