"""Generate the 17 SynhalEES task files for Kaggle Benchmarks.

Outputs to ``kaggle/tasks/``:

- 15 pillar tasks (text rows of each pillar)
- 1 vision task (all pillars, image inputs)
- 1 audio task (all pillars, audio inputs)

Regenerate whenever pillars change::

    synhalees kaggle gen              # -> kaggle/tasks/ (17 files)
    synhalees kaggle gen --dry-run    # preview only, writes nothing
    synhalees kaggle gen --out <dir>  # explicit output directory

The same script is runnable directly (``python kaggle/generate_tasks.py``).
A bare positional path is read as the output directory, so use ``--out`` for
an explicit directory and always ``--dry-run`` to preview first.

Push everything (after ``kaggle b init -y``)::

    synhalees kaggle push             # all 17 task files
    synhalees kaggle push audio       # one task (uploaded as synhalees-audio)
    synhalees kaggle push --wait      # all 17, then wait for the builds
"""

from __future__ import annotations

from pathlib import Path

from synhalees import data as syn_data

OUT_DIR = Path(__file__).resolve().parent / "tasks"
TEMPLATE = r"""
# SynhalEES Kaggle task: @TITLE@ (@MODALITY@). Auto-generated by kaggle/generate_tasks.py.

import subprocess
import sys

subprocess.run(
    [sys.executable, "-m", "pip", "install", "-q",
     "git+https://github.com/SynhalaAI/SynhalEES-Benchmark.git"],
    check=True,
)

import kaggle_benchmarks as kbench

from synhalees import data as syn_data
from synhalees.evaluators import score_response

# pip installs only the synhalees package; benchmark_data/ lives at the repo
# root and does NOT ship inside site-packages, so list_pillars() cannot find
# it. Bootstrap data from the public repo into /tmp and override data_dir.
import io
import urllib.request
import zipfile
from pathlib import Path

REPO_RAW = "https://raw.githubusercontent.com/SynhalaAI/SynhalEES-Benchmark/main"
_PILLARS = (
    "01_buddhist_culture",
    "02_pali_gatha",
    "03_classical_literature",
    "04_kavi_sindu",
    "05_sinhala_grammar",
    "06_daily_spoken",
    "07_figurative_sinhala",
    "08_profanity_nuance",
    "09_singlish_sms",
    "10_regional_dialects",
    "11_astrology_beliefs",
    "12_general_knowledge",
    "13_sri_lanka_law",
    "14_culinary_kitchen",
    "15_numbers_maths",
)

DATA_ROOT = Path("/tmp/synhalees_benchmark_data")
PILLAR = @PILLAR@  # None -> all pillars
MODALITY = "@MODALITY@"

if MODALITY in ("vision", "audio"):
    # Vision and audio tasks need media files (.jpg, .png, .mp3, etc.)
    # Download and extract benchmark_data/ from the repo archive if missing.
    _marker = DATA_ROOT / f".synhalees_{MODALITY}_ready"
    if not _marker.is_file():
        DATA_ROOT.mkdir(parents=True, exist_ok=True)
        _req = urllib.request.Request(
            "https://github.com/SynhalaAI/SynhalEES-Benchmark/archive/refs/heads/main.zip",
            headers={"User-Agent": "SynhalEES-Kaggle-Benchmark"},
        )
        _zip_data = urllib.request.urlopen(_req, timeout=120).read()
        _zf = zipfile.ZipFile(io.BytesIO(_zip_data))
        _prefix = "SynhalEES-Benchmark-main/benchmark_data/"
        for _name in _zf.namelist():
            if _name.startswith(_prefix) and not _name.endswith("/"):
                _rel = _name[len(_prefix):]
                _target = DATA_ROOT / _rel
                _target.parent.mkdir(parents=True, exist_ok=True)
                _target.write_bytes(_zf.read(_name))
        _marker.write_text("ok", encoding="utf-8")
else:
    for _p in _PILLARS:
        _f = DATA_ROOT / _p / "text.csv"
        if not _f.is_file():
            _f.parent.mkdir(parents=True, exist_ok=True)
            _f.write_text(
                urllib.request.urlopen(
                    f"{REPO_RAW}/benchmark_data/{_p}/text.csv", timeout=60
                ).read().decode("utf-8"),
                encoding="utf-8",
            )

syn_data._DEFAULT_DATA_DIR = DATA_ROOT

_JUDGE_CRITERIA = (
    "The response conveys the same meaning as the reference answer: "
    "'{ground_truth}'. Wording may differ; the meaning must match.",
    "The response reads like a native Sri Lankan Sinhala speaker wrote it -- "
    "natural register and idiom, not translated-sounding English.",
)


def _rows():
    pillars = [PILLAR] if PILLAR else syn_data.list_pillars()
    rows = []
    for pillar in pillars:
        if MODALITY == "text":
            for it in syn_data.load_text(pillar):
                rows.append({"id": it.id, "prompt": it.prompt,
                             "ground_truth": it.ground_truth,
                             "eval_type": it.eval_type, "media_path": ""})
        else:
            loader = syn_data.load_vision if MODALITY == "vision" else syn_data.load_audio
            try:
                items = loader(pillar, strict=False)
            except FileNotFoundError:
                items = []
            for it in items:
                media = it.image_path if MODALITY == "vision" else it.audio_path
                if media.is_file():
                    rows.append({"id": it.id, "prompt": it.question,
                                 "ground_truth": it.ground_truth,
                                 "eval_type": it.eval_type,
                                 "media_path": str(media)})
    choices = sorted({row["ground_truth"] for row in rows if row["eval_type"] == "classification"})
    for row in rows:
        row["choices"] = " / ".join(choices)
    return rows


@kbench.task(name="@TASK_NAME@_item", store_task=False)
def synhalees_item(llm, id: str, prompt: str, ground_truth: str,
                   eval_type: str, media_path: str = "", choices: str = "") -> dict:
    '''Score one item (sub-task; not stored top-level).'''
    if eval_type == "classification" and choices:
        prompt = "Choose exactly one label from [" + choices + "]. Reply with only the label. " + prompt
    if MODALITY == "vision":
        from kaggle_benchmarks.content_types import images
        response = llm.prompt(prompt, image=images.from_path(media_path))
    elif MODALITY == "audio":
        from kaggle_benchmarks.content_types import audios
        response = llm.prompt(prompt, audio=audios.from_path(media_path))
    else:
        response = llm.prompt(prompt)

    judge_passed = None
    if eval_type == "llm_judge":
        report = kbench.assertions.assess_response_with_judge(
            criteria=[c.format(ground_truth=ground_truth) for c in _JUDGE_CRITERIA],
            response_text=response,
            judge_llm=kbench.judge_llm,
        )
        judge_passed = all(r.passed for r in report.results)
    return {"id": id, "is_correct": score_response(
        response, ground_truth, eval_type, judge_passed=judge_passed)}


@kbench.task(name="@TASK_NAME@", description="@DESC@")
def synhalees_task(llm) -> float:
    '''Evaluate @TITLE@ (@MODALITY@); return accuracy in [0, 1].'''
    import pandas as pd

    rows = _rows()
    if not rows:
        raise ValueError(
            "No runnable @MODALITY@ rows for @TITLE@ yet -- media files may "
            "not be committed under benchmark_data/."
        )
    with kbench.client.enable_cache():
        runs = synhalees_item.evaluate(
            llm=[llm], evaluation_data=pd.DataFrame(rows),
            n_jobs=2, max_attempts=2, on_failure="continue",
            remove_run_files=True,
        )
    correct = runs.as_dataframe().result.str.get("is_correct").astype("boolean").fillna(False)
    return float(correct.mean())


# Required by the Kaggle Benchmarks workflow: the file executes the task.
synhalees_task.run(kbench.llm)
""".lstrip()
def _render(pillar, modality, task_name, title, desc) -> str:
    return (
        TEMPLATE
        .replace("@PILLAR@", repr(pillar))
        .replace("@MODALITY@", modality)
        .replace("@TASK_NAME@", task_name)
        .replace("@TITLE@", title)
        .replace("@DESC@", desc)
    )


def parse_args(argv):
    """``argv[1:]`` -> ``(out_dir, dry_run)``.

    A bare path is still read as the output directory (back-compat). Options
    must be explicit: ``--out DIR`` / ``--dry-run``. Unknown options are
    rejected because a stray flag used to be taken as the directory name and
    silently created a junk folder such as ``--dry-run/`` at the repo root
    (see AGENTS.md "Output Hygiene").
    """
    out_dir, dry = OUT_DIR, False
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg in ("--dry-run", "-n"):
            dry = True
        elif arg == "--out":
            i += 1
            if i >= len(argv):
                raise SystemExit("--out needs a directory, e.g. --out kaggle/tasks")
            out_dir = Path(argv[i])
        elif arg.startswith("-"):
            raise SystemExit(
                f"unknown option {arg!r}: pass a bare path or --out <dir> to "
                "choose the output directory, and --dry-run to preview"
            )
        else:
            out_dir = Path(arg)
        i += 1
    return out_dir, dry


def main() -> None:
    import sys

    out_dir, dry = parse_args(sys.argv[1:])
    written = []

    def emit(name, text):
        """Stage one task file (written only when not a dry run)."""
        path = out_dir / name
        written.append(path)
        if not dry:
            path.write_text(text, encoding="utf-8")

    if not dry:
        out_dir.mkdir(parents=True, exist_ok=True)

    for slug in syn_data.list_pillars():
        title = slug.partition("_")[2].replace("_", " ").title()
        emit(
            f"{slug}.py",
            _render(
                slug, "text", f"synhalees_{slug}", title,
                f"SynhalEES pillar {slug}: native Sinhala text accuracy.",
            ),
        )

    for modality in ("vision", "audio"):
        emit(
            f"{modality}.py",
            _render(
                None, modality, f"synhalees_{modality}", f"All Pillars ({modality})",
                f"SynhalEES {modality} modality across all 15 pillars.",
            ),
        )

    verb = "Would write" if dry else "Generated"
    print(f"{verb} {len(written)} task files in {out_dir}" + (" (dry run)" if dry else ""))


if __name__ == "__main__":
    main()